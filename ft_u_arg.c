#include "ft_printf.h"

int	ft_u_arg(unsigned int n)
{
	size_t	len;

	len = 0;
	if (n >= 10)
		ft_u_arg(n / 10);
	ft_putchar(n % 10 + 48);
	len++;
	return (len);
}
